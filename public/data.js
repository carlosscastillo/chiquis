// Cuánto subir (kg) cuando toca subir peso (se configura por perfil)
export function increment(user, ex) {
  const e = EXERCISES[ex];
  const inc = USERS[user]?.incrementos || { superior: 2.5, inferior: 5 };
  if (!e) return inc.superior;
  return e.lower ? inc.inferior : inc.superior;
}

